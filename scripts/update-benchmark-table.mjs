/**
 * Regenerate the website's benchmark tables from the harness's measured results.
 *
 * ⚑ WHY: the first version of that band was hand-written, and one of its numbers
 * was wrong — it quoted the colour+touching cell as if it were the all-figures
 * row. A figure retyped by hand will eventually be retyped wrong and nothing
 * will notice. After this, improving the extractor and updating the site is:
 *
 *     (in plottracer-benchmarks)  harness/run.sh
 *                                 node harness/emit-results.mjs ... --out results/latest.json
 *     (here)                      npm run benchmarks:update -- <path-to-results.json>
 *
 * The generated block sits between two HTML comment markers and is replaced
 * wholesale. Everything outside them — the prose, the citations, the "where it
 * fails" list, the invitation — is hand-written and left alone, because that is
 * judgement rather than measurement.
 *
 * Usage: node scripts/update-benchmark-table.mjs [results.json]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const RESULTS = process.argv[2] ?? path.join(process.env['HOME'] ?? '', 'code/plottracer-benchmarks/results/latest.json');
const PAGE = new URL('../docs/index.html', import.meta.url).pathname;
const START = '<!-- BENCHMARK-TABLES:START (generated by scripts/update-benchmark-table.mjs — do not edit by hand) -->';
const END = '<!-- BENCHMARK-TABLES:END -->';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const n = (v) => v.toLocaleString('en-GB');

/** Citations live HERE, not in the results file: they are bibliography, not
 *  measurement, and they change only when the corpus version does. */
const CITATIONS = {
  pmc: `UB-UNITEC PMC — charts from open-access PubMed Central papers.
          Davila, Xu, Ahmed, Mendoza, Setlur &amp; Govindaraju,
          &ldquo;ICPR 2022: Challenge on Harvesting Raw Tables from Infographics,&rdquo;
          <i>ICPR</i> 2022, 4995&ndash;5001.
          <a href="https://doi.org/10.1109/ICPR56361.2022.9956289">doi:10.1109/ICPR56361.2022.9956289</a>`,
  adobe: `Adobe CHART-Synthetic — matplotlib-generated from real data.
          Davila, Kota, Setlur, Govindaraju, Tensmeyer, Shekhar &amp; Chaudhry,
          &ldquo;ICDAR 2019 Competition on Harvesting Raw Tables from Infographics,&rdquo;
          <i>ICDAR</i> 2019, 1594&ndash;1599.
          <a href="https://doi.org/10.1109/ICDAR.2019.00203">doi:10.1109/ICDAR.2019.00203</a>`,
};

const LABEL = { bar: 'Bar', line: 'Line', scatter: 'Scatter' };

/**
 * Below this many figures a bucket is not a result, it is an anecdote.
 *
 * ⚑ Adobe's corpus has exactly ONE greyscale line chart. Rendered plainly that
 * cell read "14.3%" beside genuine 200-figure numbers — indistinguishable from a
 * measurement, and the reader has no way to know it is n=1. Suppressed instead,
 * which is the same discipline the app itself follows: do not report what you
 * cannot support (feedback_do_not_report_what_you_cannot_identify).
 */
const MIN_FIGURES = 5;

/** One decimal, always — so 92 does not print as "92%" beside "87.8%". */
const pct = (v) => `${v.toFixed(1)}%`;

function cell(bucket) {
  if (!bucket) return '<td class="sub">&mdash;</td>';
  if (bucket.figures < MIN_FIGURES) {
    return `<td class="sub" title="only ${bucket.figures} figure${bucket.figures === 1 ? '' : 's'} in this corpus — too few to report">n/a</td>`;
  }
  return `<td class="sub">${pct(bucket.pct)}</td>`;
}

function typeRow(t) {
  const size = `${n(t.all.figures)} figs &middot; ${n(t.all.total)} ${t.unit}`;
  const cells = [
    `<td>${LABEL[t.family] ?? esc(t.family)} <span class="sub">${size}</span></td>`,
    `<td class="n">${pct(t.all.pct)}</td>`,
    cell(t.colour),
    cell(t.greyscale),
  ];
  return `            <tr>${cells.join('')}</tr>`;
}

function corpusCard(c) {
  // Order the rows by result, worst last, so the honest part is not buried.
  const types = [...c.types].sort((a, b) => b.all.pct - a.all.pct);
  return `      <div class="ev-card">
        <h3>${esc(c.kind)}</h3>
        <p class="ev-cite">
          ${CITATIONS[c.id] ?? esc(c.name)}
        </p>
        <div class="ev-scroll">
        <table class="ev">
          <thead><tr><th>Chart type</th><th>Found</th><th>Colour</th><th>Greyscale</th></tr></thead>
          <tbody>
${types.map(typeRow).join('\n')}
          </tbody>
        </table>
        </div>
      </div>`;
}

const results = JSON.parse(readFileSync(RESULTS, 'utf8'));
const totalFigures = results.corpora.reduce((a, c) => a + c.figures, 0);

const block = `${START}
    <div class="ev-tables">
${results.corpora.map(corpusCard).join('\n\n')}
    </div>
    <p class="ev-stamp">
      ${n(totalFigures)} charts scored against PlotTracer
      <span class="data">${esc(results.appVersion)}</span>, measured
      ${esc(results.measured)}, at the app's own defaults
      (tolerance ${results.settings.tolerance}, minimum blob diameter
      ${results.settings.minBlobDiameter}), in ${esc(results.settings.space)} space.
      Regenerated from the harness's own output &mdash; these figures are not typed by hand.
    </p>
    ${END}`;

const page = readFileSync(PAGE, 'utf8');
const a = page.indexOf(START);
const b = page.indexOf(END);
if (a === -1 || b === -1) {
  console.error(`Markers not found in ${PAGE}. Expected:\n  ${START}\n  ${END}`);
  process.exit(1);
}
const updated = page.slice(0, a) + block + page.slice(b + END.length);
writeFileSync(PAGE, updated);

console.log(`Updated ${path.relative(process.cwd(), PAGE)} from ${RESULTS}`);
for (const c of results.corpora) {
  console.log(`  ${c.name}: ${c.types.map((t) => `${t.family} ${t.all.pct}%`).join(' · ')}`);
}
