/**
 * Regenerate the website's benchmark table from the harness's measured results.
 *
 * ⚑ THE FORM IS A PLAIN COMPARATIVE TABLE WITH NUMBERED REFERENCES (David,
 * 2026-08-01): one table, a column per corpus, corpora cited as [1] and [2] -
 * and [3] when our own open-access corpus exists. Not two cards each carrying
 * its own inline citation, which read as marketing and hid the comparison,
 * which is the interesting part.
 *
 * ⚑ THE REGISTER IS MEASURED, NOT ADVERSARIAL. An earlier version of this band
 * performed its honesty - "published the misses", "not our own samples",
 * "stated plainly" - and every one of those implies somebody else does the
 * opposite. David: *"What was and is there sounds like an attack on the others.
 * We want a balanced and measured test. That is all. That we can be honest
 * about."* State method, numbers and limitations. Claim nothing about anyone
 * else.
 *
 * ⚑ Reference numbers are POSITIONAL, from the order corpora appear in
 * results/latest.json - so adding a third corpus adds column [3] and reference
 * [3] with no edit here. That is why they are not hardcoded.
 *
 * ⚑ WHY GENERATED: the first version of this band was hand-written and one of
 * its figures was wrong - it quoted the colour+touching cell as the all-figures
 * row. A number retyped by hand is eventually retyped wrong and nothing
 * notices. Everything between the markers is measurement; the prose around them
 * is judgement and stays hand-written.
 *
 *   (in plottracer-benchmarks)  harness/run.sh && node harness/emit-results.mjs …
 *   (here)                      npm run benchmarks:update
 *
 * Usage: node scripts/update-benchmark-table.mjs [results.json]
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const RESULTS = process.argv[2] ?? path.join(process.env['HOME'] ?? '', 'code/plottracer-benchmarks/results/latest.json');
// ⚑ The evidence band lives on its own page since 2026-09-01: the home page says
// what the tool does, this one says how well. Point the generator at where the
// markers actually are, or a run silently rewrites nothing.
const PAGE = new URL('../docs/accuracy.html', import.meta.url).pathname;
// ⚑⚑ The HOME page quotes two of these numbers as its hook, and that copy was
// typed by hand - so it still said 76.1% after the tag re-run moved bars to
// 76.4%. Two pages now, because a number a reader sees is a number that must be
// generated, wherever it is shown.
const HOME = new URL('../docs/index.html', import.meta.url).pathname;
const TE_START = '<!-- BENCHMARK-TEASER:START (generated - do not edit by hand) -->';
const TE_END = '<!-- BENCHMARK-TEASER:END -->';
const START = '<!-- BENCHMARK-TABLES:START (generated by scripts/update-benchmark-table.mjs - do not edit by hand) -->';
const END = '<!-- BENCHMARK-TABLES:END -->';
/**
 * The manual-capture sentence in the Method paragraph.
 *
 * ⚑⚑ IT USED TO BE HAND-WRITTEN, AND IT WENT STALE EXACTLY AS THIS FILE'S OWN
 * header predicts. The page carried "262 bar figures ... 83.8% of 4,074 bars"
 * for three weeks after the harness had been repaired and was scoring 344
 * figures. The rule that already governs the table governs this too: the prose
 * around a number is judgement and stays hand-written, but the NUMBER is a
 * measurement and must be generated.
 */
const O_START = '<!-- BENCHMARK-OCR:START (generated - do not edit by hand) -->';
const O_END = '<!-- BENCHMARK-OCR:END -->';
// ⚑⚑ The assisted numbers were HAND-TYPED in prose until 2026-09-01, which is
// the one thing this script exists to prevent: latest.json already carried
// deltaPts, and the page carried a copy of it that nothing kept in step.
const A_START = '<!-- BENCHMARK-ASSISTED:START (generated - do not edit by hand) -->';
const A_END = '<!-- BENCHMARK-ASSISTED:END -->';
const M_START = '<!-- BENCHMARK-MANUAL:START (generated - do not edit by hand) -->';
const M_END = '<!-- BENCHMARK-MANUAL:END -->';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const num = (v) => v.toLocaleString('en-GB');
const pct = (v) => `${v.toFixed(1)}%`;

/** Bibliography. Not measurement, so it lives here rather than in the results
 *  file; it changes only when a corpus version does. */
const REFERENCES = {
  pmc: {
    short: 'Real figures',
    note: 'Charts from open-access PubMed Central papers.',
    citation:
      'K. Davila, F. Xu, S. Ahmed, D. A. Mendoza, S. Setlur and V. Govindaraju, ' +
      '&ldquo;ICPR 2022: Challenge on Harvesting Raw Tables from Infographics (CHART-Infographics),&rdquo; ' +
      '<i>26th Int. Conf. on Pattern Recognition</i>, 2022, pp. 4995&ndash;5001.',
    doi: '10.1109/ICPR56361.2022.9956289',
  },
  adobe: {
    short: 'Synthetic figures',
    note: 'Generated with matplotlib from real data sources.',
    citation:
      'K. Davila, B. U. Kota, S. Setlur, V. Govindaraju, C. Tensmeyer, S. Shekhar and R. Chaudhry, ' +
      '&ldquo;ICDAR 2019 Competition on Harvesting Raw Tables from Infographics (CHART-Infographics),&rdquo; ' +
      '<i>Int. Conf. on Document Analysis and Recognition</i>, 2019, pp. 1594&ndash;1599.',
    doi: '10.1109/ICDAR.2019.00203',
  },
};

const LABEL = { bar: 'Bar', line: 'Line', scatter: 'Scatter' };
/** Fixed row order, so two regenerations of the table can be compared. */
const ROW_ORDER = ['bar', 'line', 'scatter'];

const results = JSON.parse(readFileSync(RESULTS, 'utf8'));
const corpora = results.corpora;

function cell(corpus, family) {
  const t = corpus.types.find((x) => x.family === family);
  if (!t) return '<td class="ev-na">-</td>';
  return `<td><span class="ev-val">${pct(t.all.pct)}</span><span class="ev-n">n = ${num(t.all.total)}</span></td>`;
}

const head = corpora.map((c, i) => `<th scope="col">[${i + 1}] ${esc(REFERENCES[c.id]?.short ?? c.name)}</th>`).join('');

const rows = ROW_ORDER.filter((f) => corpora.some((c) => c.types.some((t) => t.family === f)))
  .map((f) => `            <tr><th scope="row">${LABEL[f]}</th>${corpora.map((c) => cell(c, f)).join('')}</tr>`)
  .join('\n');

const refs = corpora
  .map((c, i) => {
    const r = REFERENCES[c.id];
    const body = r
      ? `${r.citation} doi:<a href="https://doi.org/${r.doi}">${r.doi}</a>`
      : esc(c.name);
    const note = r ? ` ${r.note} ${num(c.figures)} figures scored.` : '';
    return `      <li><span class="ev-refnum">[${i + 1}]</span> ${body}<span class="ev-refnote">${note}</span></li>`;
  })
  .join('\n');

const block = `${START}
    <div class="ev-scroll">
      <table class="ev-results">
        <thead><tr><th scope="col">Chart type</th>${head}</tr></thead>
        <tbody>
${rows}
        </tbody>
      </table>
    </div>
    <p class="ev-stamp">
      Share of elements recovered within the competition's tolerance, scored in image space
      by automatic extraction. PlotTracer <span class="data">${esc(results.appVersion)}</span> at its
      default settings (tolerance ${results.settings.tolerance}, minimum blob diameter
      ${results.settings.minBlobDiameter}), measured ${esc(results.measured)}.
    </p>
    <ol class="ev-refs">
${refs}
    </ol>
    ${END}`;

/**
 * ⚑⚑ EVERY MEASURED PATH IS PRESENTED AS A RESULT, not as a sentence inside the
 * method note. Until 2026-09-01 only the automatic table was, and the assisted,
 * manual and label-reading numbers sat 900 characters into a single paragraph of
 * prose. David went to the published page looking for the label-reading number he
 * had commissioned that morning, and could not find it. A measurement a reader
 * cannot locate has not been reported, whatever the page technically contains.
 */

/** What the two declarations in the calibration walk are worth, as a table. */
const assistedRows = corpora
  .filter((c) => c.assisted)
  .map((c, i) => {
    const a = c.assisted;
    return `            <tr><th scope="row">[${i + 1}] ${esc(REFERENCES[c.id]?.short ?? c.name)}</th>` +
      `<td><span class="ev-val">${pct(a.autoPct)}</span><span class="ev-n">automatic</span></td>` +
      `<td><span class="ev-val">${pct(a.assistedPct)}</span><span class="ev-n">assisted</span></td>` +
      `<td><span class="ev-val">+${a.deltaPts}</span><span class="ev-n">points, n = ${num(a.bars)} bars</span></td></tr>`;
  })
  .join('\n');

const assistedBlock = assistedRows
  ? `${A_START}
    <div class="ev-scroll">
      <table class="ev-results">
        <thead><tr><th scope="col">Corpus</th><th scope="col">Automatic</th><th scope="col">Assisted</th><th scope="col">Difference</th></tr></thead>
        <tbody>
${assistedRows}
        </tbody>
      </table>
    </div>
    <p class="ev-stamp">
      Bar recall, with and without the two things a person declares in the calibration
      walk: the marked category axis, and the baseline the bars stand on. Nothing else
      differs. This is a ceiling rather than a user's day, because those declarations come
      from the corpus placed exactly. The second corpus is where hatched fills are common.
    </p>
    ${A_END}`
  : null;

/** Reading the chart's own WORDS. Its own result, never folded into the table. */
const o = results.ocr;
const ocrBlock = o
  ? `${O_START}
    <div class="ev-scroll">
      <table class="ev-results">
        <thead><tr><th scope="col">Read</th><th scope="col">Exactly right</th><th scope="col">Figures</th></tr></thead>
        <tbody>
            <tr><th scope="row">Tick labels [1]</th><td><span class="ev-val">${pct(o.pct)}</span><span class="ev-n">${num(o.exact)} of ${num(o.labels)}</span></td><td><span class="ev-val">${num(o.charts)}</span><span class="ev-n">real published figures</span></td></tr>
        </tbody>
      </table>
    </div>
    <p class="ev-stamp">
      Matched character for character against the corpus's own transcription of each
      label, with no partial credit. Those are the labels printed level, ${pct(
        Math.round((1000 * o.labels) / (o.labels + o.anglesSkipped)) / 10
      )} of every
      tick label in that corpus. Recovering a chart's NAMES is a different question from
      recovering its VALUES, so it is reported on its own: a tool can be good at one and
      poor at the other, and a single blended percentage would hide both.
    </p>
    ${O_END}`
  : null;

/** The manual path: the application's own capture session, scored in DATA space. */
const m = results.manual;
const excluded = Object.values(m?.excluded ?? {}).reduce((x, y) => x + y, 0);
const manualBlock = m
  ? `${M_START}
    <div class="ev-scroll">
      <table class="ev-results">
        <thead><tr><th scope="col">Captured by hand</th><th scope="col">Within 1%</th><th scope="col">Figures</th></tr></thead>
        <tbody>
            <tr><th scope="row">Bars [1]</th><td><span class="ev-val">${pct(m.barsPct)}</span><span class="ev-n">${num(m.barsWithin)} of ${num(m.bars)} bars</span></td><td><span class="ev-val">${pct(m.figuresPct)}</span><span class="ev-n">${num(m.figuresFullyWithin)} of ${num(m.figures)} with every bar within</span></td></tr>
        </tbody>
      </table>
    </div>
    <p class="ev-stamp">
      Driving the application's own capture session, with the calibration recovered from
      each figure's own tick labels and two corners clicked per bar. Scored in DATA space,
      in the figure's own units, at 1% of the value range - the only one of these paths
      measured in the units a user actually reads. ${num(excluded)} figures are excluded,
      most for carrying no two numeric tick labels to calibrate from.
    </p>
    ${M_END}`
  : null;

const page = readFileSync(PAGE, 'utf8');
const a = page.indexOf(START);
const b = page.indexOf(END);
if (a === -1 || b === -1) {
  console.error(`Markers not found in ${PAGE}`);
  process.exit(1);
}
let out = page.slice(0, a) + block + page.slice(b + END.length);

/**
 * Splice each generated region in by its own markers.
 *
 * ⚑ A MISSING MARKER IS A HARD FAILURE, never a skip: the whole point of
 * generating these is that the page cannot quietly hold a stale number, and a
 * silent skip would restore exactly that.
 */
for (const [name, s0, s1, body] of [
  ['assisted', A_START, A_END, assistedBlock],
  ['OCR', O_START, O_END, ocrBlock],
  ['manual-capture', M_START, M_END, manualBlock],
]) {
  if (!body) continue;
  const c = out.indexOf(s0);
  const d = out.indexOf(s1);
  if (c === -1 || d === -1) {
    console.error(`${name} markers not found in ${PAGE}`);
    process.exit(1);
  }
  out = out.slice(0, c) + body + out.slice(d + s1.length);
}
writeFileSync(PAGE, out);

// The home page's hook, from the same source as everything else.
const pmc = corpora.find((c) => c.id === 'pmc');
const pick = (f) => pmc?.types.find((t) => t.family === f)?.all.pct;
if (pmc && pick('scatter') != null && pick('bar') != null) {
  const home = readFileSync(HOME, 'utf8');
  const g0 = home.indexOf(TE_START);
  const g1 = home.indexOf(TE_END);
  if (g0 === -1 || g1 === -1) {
    console.error(`Teaser markers not found in ${HOME}`);
    process.exit(1);
  }
  const teaser = `${TE_START}<b>${pct(pick('scatter'))} of scatter points</b> and <b>${pct(pick('bar'))} of bars</b>${TE_END}`;
  writeFileSync(HOME, home.slice(0, g0) + teaser + home.slice(g1 + TE_END.length));
  console.log(`Updated ${HOME} (home-page teaser)`);
}

// ⚑ SAY WHAT WAS WRITTEN. An earlier rewrite of this file dropped the summary and
// the script became silent, so a run and a no-op looked identical from the
// terminal - the exact failure this project has a standing rule about.
console.log(`Updated ${PAGE} from ${RESULTS}`);
for (const [i, c] of corpora.entries()) {
  const t = (f) => {
    const x = c.types.find((y) => y.family === f);
    return x ? `${f} ${pct(x.all.pct)}` : null;
  };
  console.log(`  [${i + 1}] ${c.name}: ${ROW_ORDER.map(t).filter(Boolean).join(' \u00b7 ')}`);
  if (c.assisted) {
    console.log(`      assisted bars ${pct(c.assisted.autoPct)} -> ${pct(c.assisted.assistedPct)} (+${c.assisted.deltaPts} pts)`);
  }
}
if (results.ocr) console.log(`  labels read: ${pct(results.ocr.pct)} of ${num(results.ocr.labels)}`);
if (results.manual) console.log(`  manual capture: ${pct(results.manual.barsPct)} of ${num(results.manual.bars)} bars in data space`);
